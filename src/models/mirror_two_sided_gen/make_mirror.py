# Writes SM_MirrorTwoSidedGen.obj, the two-sided mirror piece, at its real size in Unreal units.
# The mirror stands straight: the glass runs along X and faces both +Y and -Y; the pivot is the
# bottom center. In the game it is turned by 45 degrees onto the cell diagonal, like the fixed mirror.
# Material slots: Frame (painted metal), Dark (bare metal parts), Glass (mirror), Accent (yellow paint).
# Run: python make_mirror.py
import math
import os

parts = []  # (material, outline [(a, b)], extrusion axis, low, high)


def chamfered(a0, a1, b0, b1, c):
    """Rectangle a0..a1 by b0..b1 with corners cut at 45 degrees, c units each way, counter-clockwise."""
    if c <= 0:
        return [(a0, b0), (a1, b0), (a1, b1), (a0, b1)]
    return [(a0 + c, b0), (a1 - c, b0), (a1, b0 + c), (a1, b1 - c),
            (a1 - c, b1), (a0 + c, b1), (a0, b1 - c), (a0, b0 + c)]


def box(mat, x0, x1, y0, y1, z0, z1, chamfer=0.0, axis="x"):
    """Box whose edges along `axis` are chamfered."""
    if axis == "x":
        parts.append((mat, chamfered(y0, y1, z0, z1, chamfer), "x", x0, x1))
    elif axis == "y":
        parts.append((mat, chamfered(x0, x1, z0, z1, chamfer), "y", y0, y1))
    else:
        parts.append((mat, chamfered(x0, x1, y0, y1, chamfer), "z", z0, z1))


# Base: a two-step plinth with chamfered long edges and yellow strips on both long sides.
box("Frame", -44, 44, -22, 22, 0, 8, 3, "x")
box("Frame", -38, 38, -16, 16, 8, 16, 3, "x")
for s in (-1, 1):
    box("Accent", -30, 30, *sorted((s * 22, s * 22.8)), 2.5, 5.5)
    for x in (-40, 40):  # bolt heads on the plinth
        box("Dark", x - 2.5, x + 2.5, -3, 3, 8, 10)
# Posts with chamfered vertical edges, a top bar and a rail under the glass.
for x in (-36, 36):
    box("Frame", x - 5, x + 5, -9, 9, 16, 76, 2.5, "z")
    for z in (28, 52):  # bolt plates on both faces of each post
        for s in (-1, 1):
            box("Dark", x - 3, x + 3, *sorted((s * 9, s * 10.5)), z - 3, z + 3)
box("Frame", -42, 42, -9, 9, 74, 82, 2.5, "x")
box("Accent", -14, 14, -9.6, 9.6, 77, 79)  # yellow band across the top bar
box("Dark", -31, 31, -6, 6, 16, 21, 1.5, "x")
# The glass: one slab, so both sides reflect.
box("Glass", -31, 31, -1.5, 1.5, 21, 74)


def to_xyz(axis, a, b, c):
    """Point from (outline a, outline b, extrusion c) to (x, y, z)."""
    if axis == "x":
        return (c, a, b)
    if axis == "y":
        return (a, c, b)
    return (a, b, c)


verts, uvs, normals, faces = [], [], [], {}


def add_face(mat, pts, normal):
    # Winding must turn counter-clockwise around the outward normal (right hand rule).
    (x0, y0, z0), (x1, y1, z1), (x2, y2, z2) = pts[0], pts[1], pts[2]
    ux, uy, uz = x1 - x0, y1 - y0, z1 - z0
    vx, vy, vz = x2 - x0, y2 - y0, z2 - z0
    cross = (uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx)
    if sum(c * n for c, n in zip(cross, normal)) < 0:
        pts = list(reversed(pts))
    # Box UVs: drop the axis the face points along, 100 units per texture repeat.
    k = max(range(3), key=lambda i: abs(normal[i]))
    keep = [i for i in range(3) if i != k]
    normals.append(normal)
    ni = len(normals)
    idx = []
    for p in pts:
        verts.append(p)
        uvs.append((p[keep[0]] / 100.0, p[keep[1]] / 100.0))
        idx.append(len(verts))
    faces.setdefault(mat, []).append([(i, i, ni) for i in idx])


for mat, outline, axis, lo, hi in parts:
    n = len(outline)
    # Outline is counter-clockwise in (a, b), so its outward edge normal is (db, -da).
    for c, sign in ((lo, -1), (hi, 1)):
        add_face(mat, [to_xyz(axis, a, b, c) for a, b in outline], to_xyz(axis, 0, 0, sign))
    for i in range(n):
        (a0, b0), (a1, b1) = outline[i], outline[(i + 1) % n]
        da, db = a1 - a0, b1 - b0
        length = math.hypot(da, db)
        nrm = to_xyz(axis, db / length, -da / length, 0)
        add_face(mat, [to_xyz(axis, a0, b0, lo), to_xyz(axis, a1, b1, lo),
                       to_xyz(axis, a1, b1, hi), to_xyz(axis, a0, b0, hi)], nrm)

# The OBJ importer turns OBJ (x, y, z) into Unreal (x, -y, z), so y is flipped on the way out.
# Flipping one axis mirrors the mesh, which reverses every winding as well.
lines = ["# Two-sided mirror piece, generated by make_mirror.py.", "o SM_MirrorTwoSidedGen"]
lines += [f"v {x:g} {-y:g} {z:g}" for x, y, z in verts]
lines += [f"vt {u:.4f} {v:.4f}" for u, v in uvs]
lines += [f"vn {x:.6f} {-y:.6f} {z:.6f}" for x, y, z in normals]
for mat, flist in faces.items():
    lines.append(f"usemtl {mat}")
    for f in flist:
        lines.append("f " + " ".join(f"{v}/{t}/{n}" for v, t, n in reversed(f)))

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "SM_MirrorTwoSidedGen.obj")
with open(path, "w") as fh:
    fh.write("\n".join(lines) + "\n")
print(path, len(verts), "vertices")
