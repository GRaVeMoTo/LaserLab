# Writes SM_ClockSegment.obj, one bar of the 7-segment clock, at its real size in Unreal units:
# 49 long (X), 6 deep (Y), 12 thick (Z). Each corner is cut at 45 degrees with 4 unit legs,
# so the short ends keep a 4 unit straight part. Run: python make_segment.py
import math
import os

LENGTH, DEPTH, THICK, CUT = 49.0, 6.0, 12.0, 4.0
hl, ht = LENGTH / 2, THICK / 2

# Outline in (x, z), clockwise when seen from the front.
outline = [(-hl, -ht + CUT), (-hl, ht - CUT), (-hl + CUT, ht), (hl - CUT, ht),
           (hl, ht - CUT), (hl, -ht + CUT), (hl - CUT, -ht), (-hl + CUT, -ht)]
n = len(outline)

lines = ["# Clock segment for the 7-segment clock, generated by make_segment.py.",
         "o SM_ClockSegment"]
# OBJ axes: x = length, y = depth, z = thickness; the importer keeps z as Unreal Z.
for y in (DEPTH / 2, -DEPTH / 2):
    for x, z in outline:
        lines.append(f"v {x:g} {y:g} {z:g}")
lines.append("vt 0 0")
normals = [(0, 1, 0), (0, -1, 0)]
for i in range(n):
    (x0, z0), (x1, z1) = outline[i], outline[(i + 1) % n]
    dx, dz = x1 - x0, z1 - z0
    length = math.hypot(dx, dz)
    normals.append((-dz / length, 0, dx / length))
for nx, ny, nz in normals:
    lines.append(f"vn {nx:.6f} {ny:.6f} {nz:.6f}")

front = list(range(1, n + 1))
back = list(range(n + 1, 2 * n + 1))
lines.append("f " + " ".join(f"{v}/1/1" for v in front))
lines.append("f " + " ".join(f"{v}/1/2" for v in reversed(back)))
for i in range(n):
    j = (i + 1) % n
    quad = [front[i], back[i], back[j], front[j]]
    lines.append("f " + " ".join(f"{v}/1/{3 + i}" for v in quad))

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "SM_ClockSegment.obj")
with open(path, "w") as f:
    f.write("\n".join(lines) + "\n")
print(path)
