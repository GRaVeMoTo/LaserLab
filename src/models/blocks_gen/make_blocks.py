# Writes three blocking piece meshes at their real size in Unreal units (about 80 wide, 70-80 high),
# with the pivot at the bottom center:
#   SM_BlockTank.obj      generator tank: round body on a plate, yellow bands, a green status light
#   SM_BlockRack.obj      server cabinet: LED rows and vent slots on the front and back
#   SM_BlockHeatsink.obj  laser absorber: a heavy base with cooling fins and yellow corner marks
# Material slots: Paint (painted metal, tinted per block), Dark (bare metal), Accent (yellow paint),
# Light (glowing lamp). Run: python make_blocks.py
import math
import os


class Mesh:
    def __init__(self):
        self.verts, self.uvs, self.normals, self.faces = [], [], [], {}

    def face(self, mat, pts, normal):
        # Winding turns counter-clockwise around the outward normal (right hand rule).
        (x0, y0, z0), (x1, y1, z1), (x2, y2, z2) = pts[0], pts[1], pts[2]
        u = (x1 - x0, y1 - y0, z1 - z0)
        v = (x2 - x0, y2 - y0, z2 - z0)
        cross = (u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0])
        if sum(c * n for c, n in zip(cross, normal)) < 0:
            pts = list(reversed(pts))
        # Box UVs: drop the axis the face points along, 100 units per texture repeat.
        k = max(range(3), key=lambda i: abs(normal[i]))
        keep = [i for i in range(3) if i != k]
        self.normals.append(normal)
        ni = len(self.normals)
        idx = []
        for p in pts:
            self.verts.append(p)
            self.uvs.append((p[keep[0]] / 100.0, p[keep[1]] / 100.0))
            idx.append(len(self.verts))
        self.faces.setdefault(mat, []).append([(i, i, ni) for i in idx])

    def prism(self, mat, outline, axis, lo, hi):
        """Extrude a counter-clockwise outline (a, b) along axis from lo to hi."""
        def xyz(a, b, c):
            return {"x": (c, a, b), "y": (a, c, b), "z": (a, b, c)}[axis]
        for c, sign in ((lo, -1), (hi, 1)):
            self.face(mat, [xyz(a, b, c) for a, b in outline], xyz(0, 0, sign))
        n = len(outline)
        for i in range(n):
            (a0, b0), (a1, b1) = outline[i], outline[(i + 1) % n]
            da, db = a1 - a0, b1 - b0
            ln = math.hypot(da, db)
            self.face(mat, [xyz(a0, b0, lo), xyz(a1, b1, lo), xyz(a1, b1, hi), xyz(a0, b0, hi)],
                      xyz(db / ln, -da / ln, 0))

    def box(self, mat, x0, x1, y0, y1, z0, z1, chamfer=0.0, axis="z"):
        lo, hi = {"x": (x0, x1), "y": (y0, y1), "z": (z0, z1)}[axis]
        a0, a1, b0, b1 = {"x": (y0, y1, z0, z1), "y": (x0, x1, z0, z1), "z": (x0, x1, y0, y1)}[axis]
        self.prism(mat, chamfered(a0, a1, b0, b1, chamfer), axis, lo, hi)

    def cylinder(self, mat, cx, cy, r, z0, z1, sides=20):
        pts = [(cx + r * math.cos(2 * math.pi * i / sides), cy + r * math.sin(2 * math.pi * i / sides))
               for i in range(sides)]
        self.prism(mat, pts, "z", z0, z1)

    def write(self, path, name):
        # The OBJ importer turns OBJ (x, y, z) into Unreal (x, -y, z), so y is flipped on the way out,
        # which mirrors the mesh and reverses every winding as well.
        lines = [f"# {name}, generated by make_blocks.py.", f"o {name}"]
        lines += [f"v {x:g} {-y:g} {z:g}" for x, y, z in self.verts]
        lines += [f"vt {u:.4f} {v:.4f}" for u, v in self.uvs]
        lines += [f"vn {x:.6f} {-y:.6f} {z:.6f}" for x, y, z in self.normals]
        for mat, flist in self.faces.items():
            lines.append(f"usemtl {mat}")
            for f in flist:
                lines.append("f " + " ".join(f"{v}/{t}/{n}" for v, t, n in reversed(f)))
        with open(path, "w") as fh:
            fh.write("\n".join(lines) + "\n")


def chamfered(a0, a1, b0, b1, c):
    """Rectangle a0..a1 by b0..b1 with corners cut at 45 degrees, counter-clockwise."""
    if c <= 0:
        return [(a0, b0), (a1, b0), (a1, b1), (a0, b1)]
    return [(a0 + c, b0), (a1 - c, b0), (a1, b0 + c), (a1, b1 - c),
            (a1 - c, b1), (a0 + c, b1), (a0, b1 - c), (a0, b0 + c)]


def tank():
    m = Mesh()
    m.box("Dark", -40, 40, -40, 40, 0, 6, 6)
    for x in (-33, 33):  # bolt heads on the plate corners
        for y in (-33, 33):
            m.cylinder("Dark", x, y, 3, 6, 8, 8)
    m.cylinder("Paint", 0, 0, 33, 6, 66)
    m.cylinder("Accent", 0, 0, 33.8, 16, 21)
    m.cylinder("Accent", 0, 0, 33.8, 50, 55)
    m.cylinder("Dark", 0, 0, 26, 66, 72)
    m.cylinder("Dark", 0, 0, 9, 72, 80, 12)
    m.box("Dark", -4, 4, -36, -32, 26, 44)          # pipe running down the front
    m.box("Light", -5, 5, 32.5, 35, 36, 42)         # green status light on the back
    m.box("Light", -5, 5, -35, -32.5, 56, 61)       # and one on the front
    return m


def rack():
    m = Mesh()
    m.box("Dark", -38, 38, -34, 34, 0, 5, 3)
    m.box("Paint", -36, 36, -32, 32, 5, 76, 3)
    for s in (-1, 1):
        y_out = s * 32.6
        face = sorted((s * 32, y_out))
        for row in range(5):  # LED rows
            z = 18 + row * 11
            for col in range(4):
                x = -24 + col * 9
                m.box("Light", x - 2.5, x + 2.5, *face, z - 1.5, z + 1.5)
            m.box("Dark", 12, 30, *face, z - 2, z + 2)  # vent slot next to the LEDs
        m.box("Accent", -30, 30, *sorted((s * 32, s * 32.6)), 66, 70)  # yellow label strip
    for x in (-24, 24):  # carry handles on the top
        m.box("Dark", x - 3, x + 3, -22, 22, 76, 79)
    return m


def heatsink():
    m = Mesh()
    m.box("Dark", -40, 40, -40, 40, 0, 10, 4, "x")
    m.box("Paint", -34, 34, -34, 34, 10, 34, 3, "x")
    for i in range(7):  # cooling fins
        x = -27 + i * 9
        m.box("Paint", x - 2, x + 2, -32, 32, 34, 76, 1, "y")
    for x in (-36, 36):  # yellow corner marks on the base
        for y in (-36, 36):
            m.box("Accent", x - 4, x + 4, y - 4, y + 4, 10, 11)
    m.box("Dark", -36, 36, -3, 3, 76, 79)  # clamp bar across the fins
    return m


here = os.path.dirname(os.path.abspath(__file__))
for name, build in (("SM_BlockTank", tank), ("SM_BlockRack", rack), ("SM_BlockHeatsink", heatsink)):
    mesh = build()
    mesh.write(os.path.join(here, name + ".obj"), name)
    print(name, len(mesh.verts), "vertices")
